// Generate example template
function generateExample(word, translation) {
  const templates = [
    {
      en: `The ${word} is an important part of university life.`,
      zh: `${translation}是大学生活的重要组成部分。`
    },
    {
      en: `Students need to understand ${word} in their studies.`,
      zh: `学生在学习中需要理解${translation}。`
    },
    {
      en: `The professor discussed ${word} in today's lecture.`,
      zh: `教授在今天的讲座中讨论了${translation}。`
    }
  ];

  // Randomly select a template
  return templates[Math.floor(Math.random() * templates.length)];
}

